for filename, title, sections in documents:
    doc = Document()
    page = doc.sections[0]
    page.page_width, page.page_height = Cm(21), Cm(29.7)
    page.top_margin = page.bottom_margin = Cm(1.8)
    page.left_margin = page.right_margin = Cm(2)
    for name, size in [('Normal', 11), ('Title', 21), ('Heading 1', 13)]:
        style = doc.styles[name]
        style.font.name = 'Arial'
        style.font.size = Pt(size)
        style.font.color.rgb = RGBColor(0, 0, 0)
        style.element.get_or_add_rPr().get_or_add_rFonts().set(qn('w:cs'), 'Arial')
        style.paragraph_format.space_after = Pt(6)
        style.paragraph_format.line_spacing = 1.12
    doc.styles['Heading 1'].paragraph_format.space_before = Pt(10)
    def para(text, style='Normal'):
        p = doc.add_paragraph(text, style)
        p.alignment = WD_ALIGN_PARAGRAPH.RIGHT
        bidi = OxmlElement('w:bidi')
        bidi.set(qn('w:val'), '1')
        p._p.get_or_add_pPr().append(bidi)
        return p
    para(title, 'Title')
    for heading, content in sections:
        para(heading, 'Heading 1')
        para(content)
    doc.core_properties.author = 'Demo Company'
    doc.core_properties.title = title
    doc.core_properties.subject = 'Fictional chatbot test document'
    path = OUT / filename
    path.parent.mkdir(parents=True, exist_ok=True)
    doc.save(path)
    print(path)

